def rezip():
    src = pathlib.Path.home() / ".claude/skills"
    for name, *_ in SKILLS:
        z = SK / f"{name}.zip"
        z.unlink(missing_ok=True)
        subprocess.run(["zip", "-X", "-q", "-r", str(z), name, "-x", "*.DS_Store", "*/node_modules/*",
                        "*/__pycache__/*", "*.bak-*"], cwd=src, check=True)


def web_variants():
    for src, dst in WEB_RENAME.items():
        out = SK / f"{dst}.zip"
        if out.exists():
            continue
        with zipfile.ZipFile(SK / f"{src}.zip") as zin, zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as zout:
            for info in zin.infolist():
                data = zin.read(info.filename)
                if info.filename == f"{src}/SKILL.md":
                    data = re.sub(rb"(?m)^name: " + src.encode() + rb"\s*$", b"name: " + dst.encode(), data, count=1)
                info2 = zipfile.ZipInfo(dst + info.filename[len(src):], info.date_time)
                info2.external_attr, info2.compress_type = info.external_attr, zipfile.ZIP_DEFLATED
                zout.writestr(info2, data)


def usage():
    text = (here / "captures/12-skill-usage-relic5.txt").read_text(encoding="utf-8")
    return {m[1]: int(m[2]) for m in re.finditer(r"│ ([a-z-]+)\s+│ (\d+)\s+│ (\d+)\s+│ 20", text)} | {}


def measure():
    uses = usage()
    rows = []
    for name, tier, web, th, en in SKILLS:
        with zipfile.ZipFile(SK / f"{name}.zip") as z:
            md = z.read(f"{name}/SKILL.md").decode("utf-8")
            files = len(z.namelist())
        rows.append(dict(name=name, tier=tier, web=web, th=th, en=en, uses=uses.get(name, 0), files=files,
                         kb=round((SK / f"{name}.zip").stat().st_size / 1024, 1),
                         deps={c: len(re.findall(rx, md)) for c, rx in DEPS}))
    return rows


