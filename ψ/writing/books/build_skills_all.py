"""Bake the rest of the ARRA Oracle skills (lesson 01's 28 ZIPs) into oracle/full/<name>.md and skills_extra.js,
so the lessons MCP hands out every skill, not only the 7 that run in a chat (Nat, 5 Nov 2026: "skill not all? from our
oracle skills?" then "you just put it in mcp?").

Source = the same ZIPs people download from lesson 01 (skills/*.zip + skills.json), so the MCP and the downloads agree.
Each file says up front whether the skill works in a chat (skills.json "web": ok / partial / local).
The 7 chat skills keep their own runbooks (build_skills_full.py); this script skips them.

Usage: python3 build_skills_all.py      AIExpo Oracle (Oracle AI), 2026-11-05.
"""
import json, pathlib, zipfile

HERE = pathlib.Path(__file__).resolve().parent
ZIPS = HERE / "2026-10-30_claude-chatgpt-install-guide" / "skills"
OUT = HERE / "oracle" / "full"
CHAT7 = {"awaken", "rrr", "forward", "recap", "workshop", "awaken-app", "where-we-are"}
LANG = {".py": "python", ".ts": "ts", ".sh": "bash", ".mjs": "js", ".js": "js", ".json": "json"}
NOTE = {
    "ok": "works in a chat: follow it with the person here. Where it mentions files or commands, show the content for the person to save.",
    "partial": "works partly in a chat: run what the chat can do; files it would write are shown for the person to save, and they are gone in the next chat unless saved. The full version needs Claude Code or Codex.",
    "local": "needs Claude Code or Codex on the person's own machine (terminal, git, files on disk). In a chat, do NOT run or imitate it: explain what it does, and give the download link and install line below.",
}

meta = json.loads((ZIPS / "skills.json").read_text(encoding="utf-8"))
extra = {}
for s in meta["skills"]:
    name = s["name"]
    if name in CHAT7: continue
    z = zipfile.ZipFile(ZIPS / f"{name}.zip")
    files = sorted((n for n in z.namelist() if not n.endswith("/")),
                   key=lambda p: (0 if p.endswith("/SKILL.md") else 1 if p.endswith(".md") else 2, p))
    parts = []
    for p in files:
        raw = z.read(p)
        try: text = raw.decode("utf-8")
        except UnicodeDecodeError: continue   # binary assets are in the ZIP, not in the text
        ext = pathlib.PurePath(p).suffix
        body = text if ext == ".md" else f"```{LANG.get(ext, '')}\n{text.rstrip()}\n```"
        parts.append(f"<!-- file: {p} -->\n### File: `{p}`\n\n{body.rstrip()}\n")
    doc = (f"# Oracle skill `{name}`: the full skill\n\n"
           f"> For the AI: /{name} = {s['en']}. In a chat it {NOTE[s['web']]}\n"
           f"> This is every file of the skill as shipped in lesson 01 ({meta['source']}), {len(parts)} files.\n\n"
           + "\n".join(parts))
    (OUT / f"{name}.md").write_text(doc, encoding="utf-8")
    extra[name] = {"what": f"{s['th']} · {s['en']}", "web": s["web"]}
    print(f"oracle/full/{name}.md  {len(doc.encode()):,} bytes  {len(parts)} files  web={s['web']}")

(HERE / "skills_extra.js").write_text(
    "// generated by build_skills_all.py: the rest of lesson 01's ARRA Oracle skills (name -> what, web = ok|partial|local)\n"
    "export const EXTRA = " + json.dumps(extra, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
print(f"skills_extra.js  {len(extra)} skills")
