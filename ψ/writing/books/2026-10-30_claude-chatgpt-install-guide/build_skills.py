def splice(path, rows, th, first_run_start):
    p = here / path
    s = p.read_text(encoding="utf-8")
    new = f"{BEGIN}\n{block(rows, th)}\n{END}"
    if BEGIN in s:
        s = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda m: new, s, flags=re.S)
    else:  # first run: replace the hand-written block that started at first_run_start and ran to 6.2
        i = s.index(first_run_start)
        j = s.index("\n**6.2", i)
        s = s[:i] + "\n" + new + "\n" + s[j:]
    p.write_text(s, encoding="utf-8")


